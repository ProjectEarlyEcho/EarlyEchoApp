"""Real PostgreSQL migration/RLS/replay tests. Requires an explicitly disposable DB.

SYNC_TEST_DATABASE_URL=postgresql://.../earlyecho_sync_test python3 supabase/tests/test_sync_integrity.py
Use --setup-only to install the same schema/fixture for independent HTTP tests.
The fixture recreates public/auth in the named database, never server settings.
"""

import concurrent.futures
import json
import os
from pathlib import Path
import subprocess
import sys
import threading
import unittest
import uuid


ROOT = Path(__file__).resolve().parents[2]
DATABASE_URL = os.environ.get("SYNC_TEST_DATABASE_URL")
A = "00000000-0000-0000-0000-000000000001"
B = "00000000-0000-0000-0000-000000000002"
ADMIN = "00000000-0000-0000-0000-000000000003"
PARENT = "00000000-0000-0000-0000-000000000004"
LEGACY = "10000000-0000-0000-0000-000000000001"
LEGACY_CONSENT = "20000000-0000-0000-0000-000000000001"
LEGACY_OWNED = "10000000-0000-0000-0000-000000000002"
LEGACY_LINKED_CONSENT = "20000000-0000-0000-0000-000000000002"


def psql(sql, owner=None, role="authenticated", check=True):
    if owner is not None:
        sql = f"set role {role}; set request.jwt.claim.sub = '{owner}';\n" + sql
    result = subprocess.run(
        ["psql", "-X", DATABASE_URL, "-qAt", "-v", "ON_ERROR_STOP=1", "-v", "VERBOSITY=verbose"],
        input=sql, text=True, capture_output=True, timeout=30,
    )
    if check and result.returncode:
        raise AssertionError(result.stderr)
    return result


def screening(owner=A, **changes):
    return {
        "id": str(uuid.uuid4()), "created_by": owner, "anganwadi_id": "AW-001",
        "state_code": "BR", "district_code": "PAT", "child_age_months": 30,
        "risk_level": "yellow", "vttl_ms": 1840.5, "pfv_std": 2.3,
        "cvr_ratio": 0.42, "vttl_flagged": True, "pfv_flagged": False,
        "cvr_flagged": False, "audio_source": "unprocessed",
        "session_date": "2026-09-18T10:00:00.000Z", **changes,
    }


def consent(session, **changes):
    return {
        "id": str(uuid.uuid4()), "created_by": session["created_by"],
        "session_id": session["id"], "anganwadi_id": session["anganwadi_id"],
        "worker_name": "Worker", "consented_at": "2026-09-18T09:55:00.000Z",
        **changes,
    }


def rpc(name, payload):
    # JSON payloads generated by this suite are quoted as SQL string literals.
    value = json.dumps(payload).replace("'", "''")
    return f"select public.{name}('{value}'::jsonb);"


def setup_database():
    if not DATABASE_URL:
        raise SystemExit("Set SYNC_TEST_DATABASE_URL to an exclusively disposable PostgreSQL database.")
    database = psql("select current_database();").stdout.strip()
    if database in {"postgres", "template0", "template1"}:
        raise SystemExit("Refusing to reset a PostgreSQL system database.")
    psql((ROOT / "supabase/tests/auth_fixture.sql").read_text())
    psql((ROOT / "supabase/schema.sql").read_text())
    for migration in sorted((ROOT / "supabase/migrations").glob("*.sql")):
        if migration.name == "202611160001_mobile_sync_integrity.sql":
            # Existing installations contain consent with no proven author and
            # screenings whose creator is missing. Upgrading must preserve both.
            psql(f"""
              insert into auth.users(id) values ('{A}'), ('{B}'), ('{ADMIN}'), ('{PARENT}');
              update public.profiles set role = 'clinician', anganwadi_id = 'AW-001' where id in ('{A}', '{B}');
              update public.profiles set role = 'admin' where id = '{ADMIN}';
              insert into public.screenings(id, anganwadi_id) values ('{LEGACY}', 'AW-001');
               insert into public.consent_logs(id, session_id, anganwadi_id, consented_at)
               values ('{LEGACY_CONSENT}', '{LEGACY}', 'AW-001', '2026-09-18T09:55:00Z');
               insert into public.screenings(id, anganwadi_id, created_by)
               values ('{LEGACY_OWNED}', 'AW-001', '{A}');
               insert into public.consent_logs(id, session_id, anganwadi_id, consented_at)
               values ('{LEGACY_LINKED_CONSENT}', '{LEGACY_OWNED}', 'AW-001', '2026-09-18T09:55:00Z');
            """)
        psql(migration.read_text())


class SyncIntegrityTests(unittest.TestCase):
    def output(self, sql, owner=A, role="authenticated"):
        return psql(sql, owner=owner, role=role).stdout.strip()

    def denied(self, sql, owner=A, code="42501", role="authenticated"):
        result = psql(sql, owner=owner, role=role, check=False)
        self.assertNotEqual(result.returncode, 0, result.stdout)
        self.assertIn(code, result.stderr)

    def test_legacy_upgrade_retains_unowned_rows_without_adoption(self):
        self.assertEqual(self.output(f"select count(*) from public.screenings where id = '{LEGACY}';", owner=None), "1")
        self.assertEqual(self.output(f"select count(*) from public.consent_logs where id = '{LEGACY_CONSENT}' and created_by is null;", owner=None), "1")
        self.assertEqual(self.output(f"select count(*) from public.screenings where id = '{LEGACY_OWNED}' and created_by = '{A}';"), "1")
        self.assertEqual(self.output(f"select count(*) from public.consent_logs where id = '{LEGACY_LINKED_CONSENT}' and created_by is null;", owner=None), "1")
        for owner in [A, B, ADMIN, PARENT]:
            self.assertEqual(self.output(f"select count(*) from public.screenings where id = '{LEGACY}';", owner), "0")
            self.assertEqual(self.output(f"select count(*) from public.consent_logs where id = '{LEGACY_CONSENT}';", owner), "0")
            self.assertEqual(self.output(f"select count(*) from public.consent_logs where id = '{LEGACY_LINKED_CONSENT}';", owner), "0")

    def test_screening_identical_replay_normalizes_numbers_and_time(self):
        value = screening(vttl_ms=1840)
        self.assertEqual(self.output(rpc("sync_screening", value)), "inserted")
        normalized = {**value, "vttl_ms": 1840.0, "session_date": "2026-09-18T15:30:00+05:30", "created_at": "2000-01-01Z"}
        self.assertEqual(self.output(rpc("sync_screening", normalized)), "replayed")
        self.assertEqual(self.output(f"select count(*) from public.screenings where id = '{value['id']}';"), "1")

    def test_screening_conflict_never_overwrites(self):
        value = screening()
        self.output(rpc("sync_screening", value))
        self.denied(rpc("sync_screening", {**value, "risk_level": "red"}), code="PT409")
        self.assertEqual(self.output(f"select risk_level from public.screenings where id = '{value['id']}';"), "yellow")

    def test_consent_replay_conflict_and_link_integrity(self):
        value = screening()
        self.output(rpc("sync_screening", value))
        log = consent(value)
        self.assertEqual(self.output(rpc("sync_consent_log", log)), "inserted")
        self.assertEqual(self.output(rpc("sync_consent_log", log)), "replayed")
        self.assertEqual(self.output(rpc("sync_consent_log", {**log, "consented_at": "2026-09-18T15:25:00+05:30"})), "replayed")
        self.denied(rpc("sync_consent_log", {**log, "worker_name": "Different"}), code="PT409")
        self.denied(rpc("sync_consent_log", consent(value, session_id=str(uuid.uuid4()))))
        self.denied(rpc("sync_consent_log", consent(value, anganwadi_id="AW-OTHER")))
        self.assertEqual(self.output(f"select worker_name from public.consent_logs where id = '{log['id']}';"), "Worker")

    def test_other_owner_cannot_read_replay_overwrite_or_link(self):
        value = screening()
        self.output(rpc("sync_screening", value))
        log = consent(value)
        self.output(rpc("sync_consent_log", log))
        for owner in [B, ADMIN, PARENT]:
            self.assertEqual(self.output(f"select count(*) from public.screenings where id = '{value['id']}';", owner), "0")
            self.assertEqual(self.output(f"select count(*) from public.consent_logs where id = '{log['id']}';", owner), "0")
            self.denied(rpc("sync_screening", value), owner)
            self.denied(rpc("sync_consent_log", log), owner)
            self.denied(rpc("sync_consent_log", consent(value, created_by=owner)), owner)
        self.denied(rpc("sync_screening", {**value, "created_by": B}), B, code="PT409")

    def test_roles_centres_and_forged_owners_are_enforced_server_side(self):
        self.denied(rpc("sync_screening", screening(owner=PARENT)), PARENT)
        self.denied(rpc("sync_screening", screening(owner=B)), A)
        self.denied(rpc("sync_screening", screening(created_by=None)))
        self.denied(rpc("sync_screening", screening(anganwadi_id="AW-OTHER")))
        self.denied(rpc("sync_screening", screening()), owner="", role="anon")
        self.assertEqual(self.output(rpc("sync_screening", screening(owner=ADMIN, anganwadi_id="AW-OTHER")), ADMIN), "inserted")
        self.denied("update public.profiles set anganwadi_id = 'AW-OTHER' where id = auth.uid();")
        self.denied("update public.profiles set role = 'admin' where id = auth.uid();")
        self.output("update public.profiles set display_name = 'Updated worker' where id = auth.uid();")

    def test_direct_table_access_cannot_bypass_immutable_rpc_contract(self):
        value = screening()
        self.output(rpc("sync_screening", value))
        log = consent(value)
        self.output(rpc("sync_consent_log", log))
        for table, record in [("screenings", value), ("consent_logs", log)]:
            self.denied(f"delete from public.{table} where id = '{record['id']}';")
            self.denied(f"update public.{table} set created_by = '{B}' where id = '{record['id']}';")
        self.denied(f"insert into public.screenings(id, anganwadi_id, created_by) values ('{uuid.uuid4()}', 'AW-001', '{B}');")
        self.denied(f"insert into public.consent_logs(id, session_id, anganwadi_id, created_by, consented_at) values ('{uuid.uuid4()}', '{value['id']}', 'AW-001', '{B}', now());", B)

    def test_concurrent_identical_replays_create_one_screening_and_consent(self):
        value = screening()
        for name, payload in [("sync_screening", value), ("sync_consent_log", consent(value))]:
            barrier = threading.Barrier(6)
            def attempt(_):
                barrier.wait(timeout=10)
                return self.output(rpc(name, payload))
            with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
                results = list(pool.map(attempt, range(6)))
            self.assertEqual(results.count("inserted"), 1)
            self.assertEqual(results.count("replayed"), 5)

    def test_concurrent_conflicting_writers_keep_one_winner(self):
        value = screening()
        barrier = threading.Barrier(2)
        def attempt(risk):
            barrier.wait(timeout=10)
            return psql(rpc("sync_screening", {**value, "risk_level": risk}), owner=A, check=False)
        with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
            results = list(pool.map(attempt, ["green", "red"]))
        self.assertEqual(sum(result.returncode == 0 for result in results), 1)
        self.assertIn("PT409", next(result.stderr for result in results if result.returncode))
        self.assertEqual(self.output(f"select count(*) from public.screenings where id = '{value['id']}';"), "1")

    def test_transaction_rollback_and_lost_ack_can_be_retried(self):
        value = screening()
        self.output("begin; " + rpc("sync_screening", value) + " rollback;")
        self.assertEqual(self.output(rpc("sync_screening", value)), "inserted")
        # Discarded first response is equivalent to a lost HTTP acknowledgement.
        self.assertEqual(self.output(rpc("sync_screening", value)), "replayed")


