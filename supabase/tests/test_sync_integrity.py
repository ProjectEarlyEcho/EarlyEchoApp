    def test_concurrent_dashboard_conflicts_keep_a_single_consistent_winner(self):
        value = screening()
        barrier = threading.Barrier(2)
        def attempt(rule):
            barrier.wait(timeout=10)
            projection = dashboard_screening(value, decision_trace={"rule": rule})
            return psql(rpc("sync_child_screening", value, projection), owner=A, check=False)
        rules = ["first", "second"]
        with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
            results = list(pool.map(attempt, rules))
        self.assertEqual(sum(result.returncode == 0 for result in results), 1)
        self.assertIn("PT409", next(result.stderr for result in results if result.returncode))
        winner = rules[next(i for i, result in enumerate(results) if result.returncode == 0)]
        self.assertEqual(self.output(f"select decision_trace ->> 'rule' from public.screening_sessions where id = '{value['id']}';"), winner)
        for table in ["screenings", "screening_sessions"]:
            self.assertEqual(self.output(f"select count(*) from public.{table} where id = '{value['id']}';"), "1")
        self.assertEqual(self.output(rpc("sync_child_screening", value, dashboard_screening(value, decision_trace={"rule": winner}))), "replayed")

